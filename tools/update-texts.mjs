#!/usr/bin/env node
// Builds js/texts.js (typing tab) from Taqtaqa's text file (https://taqtaqa.com, repo GhofranSalem/taqtaqa).
// Usage:  node tools/update-texts.mjs path/to/taqtaqa/assets/data.js
// Copies Egyptian Arabic (Arabic interface) and English quotes (English interface), cleaned for typing.
import fs from "node:fs";
import vm from "node:vm";
import path from "node:path";

const src = process.argv[2];
if (!src) { console.error("usage: node tools/update-texts.mjs path/to/taqtaqa/assets/data.js"); process.exit(1); }

// data.js only declares constants; evaluate it in an empty sandbox and pick the sets.
const sets = vm.runInNewContext(fs.readFileSync(src, "utf8") + "\n;({KALAM,EN_QUOTES})", {}, { timeout: 2000 });

// Texts are for trying the keyboard, so keep only letters, digits and spaces:
// no tashkeel/tatweel and no punctuation (an apostrophe inside an English word stays: don't, it's).
const clean = t => String(t)
  .replace(/[\u064B-\u0652\u0670\u0640]/g, "")
  .replace(/[ﻻﻹﻷﻵ]/g, m => ({ "ﻻ": "لا", "ﻹ": "لإ", "ﻷ": "لأ", "ﻵ": "لآ" }[m]))
  .replace(/[’‘]/g, "'")
  .replace(/(?<![A-Za-z])'|'(?![A-Za-z])/g, " ")
  .replace(/[^\p{L}\p{N}' ]/gu, " ")
  .replace(/\s+/g, " ").trim();

const out = {
  ar: sets.KALAM.map(clean),                 // Egyptian Arabic
  en: sets.EN_QUOTES.map(([t]) => clean(t)), // English quotes
};
for (const k in out) out[k] = [...new Set(out[k].filter(t => t.length >= 3))];

const dest = path.join(path.dirname(new URL(import.meta.url).pathname), "..", "js", "texts.js");
fs.writeFileSync(dest,
  "// Typing texts from Taqtaqa (https://taqtaqa.com). Generated by tools/update-texts.mjs — don't edit by hand.\n" +
  "// ar = Egyptian Arabic, en = English quotes. Plain letters and spaces only.\n" +
  "export const TEXTS = " + JSON.stringify(out) + ";\n");
console.log("wrote", dest, Object.entries(out).map(([k, v]) => `${k}:${v.length}`).join(" "));
