#!/usr/bin/env node
// Builds js/texts.js (typing tab) from Taqtaqa's text file (https://taqtaqa.com, repo GhofranSalem/taqtaqa).
// Usage:  node tools/update-texts.mjs path/to/taqtaqa/assets/data.js
// Only plain-data sets are copied: proverbs, Egyptian Arabic, wisdom, poetry, stories and English quotes.
import fs from "node:fs";
import vm from "node:vm";
import path from "node:path";

const src = process.argv[2];
if (!src) { console.error("usage: node tools/update-texts.mjs path/to/taqtaqa/assets/data.js"); process.exit(1); }

// data.js only declares constants; evaluate it in an empty sandbox and pick the sets.
const sets = vm.runInNewContext(fs.readFileSync(src, "utf8") + "\n;({MASRY,SAUDI,KALAM,HEKAM,SHEER,HAWADIT,EN_QUOTES})", {}, { timeout: 2000 });

// Same cleanup Taqtaqa applies with diacritics off: no tashkeel/tatweel, no quote marks, normalised spaces.
const clean = t => String(t)
  .replace(/[ً-ْٰـ]/g, "")
  .replace(/[«»“”"]/g, "")
  .replace(/[ﻻﻹﻷﻵ]/g, m => ({ "ﻻ": "لا", "ﻹ": "لإ", "ﻷ": "لأ", "ﻵ": "لآ" }[m]))
  .replace(/\s+/g, " ").trim();
const plain = (arr, s) => arr.map(t => [clean(t), s]);
const pairs = arr => arr.map(([t, s]) => [clean(t), clean(s)]);

const out = {
  masry:   plain(sets.MASRY, "مثل شعبي مصري"),
  saudi:   plain(sets.SAUDI, "مثل شعبي سعودي"),
  kalam:   plain(sets.KALAM, "كلام مصري"),
  hekam:   pairs(sets.HEKAM),
  sheer:   pairs(sets.SHEER),
  hawadit: pairs(sets.HAWADIT),
  en:      sets.EN_QUOTES.map(([t, s]) => [String(t).replace(/\s+/g, " ").trim(), s]),
};
for (const [k, v] of Object.entries(out)) out[k] = v.filter(([t]) => t.length >= 3);

const dest = path.join(path.dirname(new URL(import.meta.url).pathname), "..", "js", "texts.js");
fs.writeFileSync(dest,
  "// Typing texts from Taqtaqa (https://taqtaqa.com). Generated by tools/update-texts.mjs — don't edit by hand.\n" +
  "// Each entry: [text, source].\n" +
  "export const TEXTS = " + JSON.stringify(out) + ";\n");
console.log("wrote", dest, Object.entries(out).map(([k, v]) => `${k}:${v.length}`).join(" "));
